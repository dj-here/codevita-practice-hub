const { PrismaClient } = require('@prisma/client');

const prisma = new PrismaClient();

async function main() {
  console.log('Seeding Phase 2 sample problem...');

  const problem = await prisma.problem.upsert({
    where: { slug: 'cv-sample-sum-of-primes' },
    update: {},
    create: {
      slug: 'cv-sample-sum-of-primes',
      title: 'Sum of Primes in Range',
      difficulty: 'EASY',
      timeLimitMs: 1000,
      memoryLimitKb: 262144,
      statement: `In the kingdom of Digitopia, the Royal Mathematician needs to calculate the energy generated by a sequence of magic stones. Each stone numbered between L and R (inclusive) emits energy equal to its value if and only if its value is a prime number. Non-prime stones emit zero energy.

Write a program that takes two integers L and R, and calculates the total energy produced by all stones in the range [L, R].`,
      inputFormat: 'A single line containing two space-separated integers L and R.',
      outputFormat: 'Print the sum of all prime numbers between L and R inclusive.',
      constraints: '1 <= L <= R <= 1000',
      editorial: 'Iterate through all integers from L to R. For each integer, check primality in O(sqrt(N)) time. Accumulate the sum of prime numbers.',
      isPublished: true,
      testCases: {
        create: [
          // Sample 1
          {
            input: '1 10',
            expectedOutput: '17',
            isSample: true,
            explanation: 'The prime numbers between 1 and 10 are 2, 3, 5, and 7. Their sum is 2 + 3 + 5 + 7 = 17.',
            orderIndex: 1,
          },
          // Sample 2
          {
            input: '10 20',
            expectedOutput: '60',
            isSample: true,
            explanation: 'The prime numbers between 10 and 20 are 11, 13, 17, and 19. Their sum is 11 + 13 + 17 + 19 = 60.',
            orderIndex: 2,
          },
          // Hidden 1: edge case L=1, R=1 (no primes)
          {
            input: '1 1',
            expectedOutput: '0',
            isSample: false,
            orderIndex: 3,
          },
          // Hidden 2: single prime
          {
            input: '2 2',
            expectedOutput: '2',
            isSample: false,
            orderIndex: 4,
          },
          // Hidden 3: range up to 100
          {
            input: '1 100',
            expectedOutput: '1060',
            isSample: false,
            orderIndex: 5,
          },
          // Hidden 4: range 50 to 100
          {
            input: '50 100',
            expectedOutput: '820',
            isSample: false,
            orderIndex: 6,
          },
          // Hidden 5: range 100 to 200
          {
            input: '100 200',
            expectedOutput: '3167',
            isSample: false,
            orderIndex: 7,
          },
        ],
      },
    },
  });

  // Attach Tag "Number Theory & Primes"
  const tag = await prisma.tag.findUnique({
    where: { slug: 'number-theory-primes' },
  });

  if (tag) {
    await prisma.problemTag.upsert({
      where: {
        problemId_tagId: {
          problemId: problem.id,
          tagId: tag.id,
        },
      },
      update: {},
      create: {
        problemId: problem.id,
        tagId: tag.id,
      },
    });
  }

  console.log(`✅ Seeded sample problem: ${problem.slug}`);
}

main()
  .catch((e) => {
    console.error(e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
